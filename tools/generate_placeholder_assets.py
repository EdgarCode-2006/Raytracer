#!/usr/bin/env python3
"""Generates the placeholder game assets: low-poly ships (.obj) and the space background (.png).

They only exist so the game can run before the real assets are made. Replace the files in
assets/game/ (or point assets/game/entities.cfg and assets/scenes/space.cfg at other files).

Run from the repository root: python3 tools/generate_placeholder_assets.py
"""

import math
import os
import struct
import zlib

import numpy as np

MODELS_DIR = "assets/game/models"
TEXTURES_DIR = "assets/game/textures"


# --- MESHES ---
# Every shape is convex and its faces are oriented outwards from its center. Each face gets
# its own vertices so that smooth shading keeps the low-poly look.

def oriented(tris):
    """Flips the triangles of a convex shape whose normal points to its inside."""
    center = np.mean([v for tri in tris for v in tri], axis=0)
    out = []
    for a, b, c in tris:
        a, b, c = np.array(a, float), np.array(b, float), np.array(c, float)
        normal = np.cross(b - a, c - a)
        if np.dot(normal, (a + b + c) / 3 - center) < 0:
            b, c = c, b
        out.append((a, b, c))
    return out


def fan(center, ring):
    return [(center, ring[i], ring[(i + 1) % len(ring)]) for i in range(len(ring))]


def strip(ring_a, ring_b):
    tris = []
    n = len(ring_a)
    for i in range(n):
        j = (i + 1) % n
        tris.append((ring_a[i], ring_a[j], ring_b[j]))
        tris.append((ring_a[i], ring_b[j], ring_b[i]))
    return tris


def ring_x(x, ry, rz, sides, y=0.0):
    """A ring around the x axis (the ships fly along x)."""
    return [(x, y + ry * math.cos(2 * math.pi * k / sides), rz * math.sin(2 * math.pi * k / sides))
            for k in range(sides)]


def ring_y(y, r, sides, x=0.0, z=0.0):
    """A ring around the y axis (for the saucer)."""
    return [(x + r * math.cos(2 * math.pi * k / sides), y, z + r * math.sin(2 * math.pi * k / sides))
            for k in range(sides)]


def prism(polygon, offset):
    """Extrudes a convex polygon by +-offset (a vector): a fin or a wing."""
    offset = np.array(offset, float)
    top = [tuple(np.array(p) + offset) for p in polygon]
    bottom = [tuple(np.array(p) - offset) for p in polygon]
    center_top = tuple(np.mean(top, axis=0))
    center_bottom = tuple(np.mean(bottom, axis=0))
    return oriented(fan(center_top, top) + fan(center_bottom, bottom) + strip(top, bottom))


def box(center, half):
    cx, cy, cz = center
    hx, hy, hz = half
    square = [(cx - hx, cy - hy, cz), (cx + hx, cy - hy, cz), (cx + hx, cy + hy, cz), (cx - hx, cy + hy, cz)]
    return prism(square, (0, 0, hz))


def octahedron(center, rx, ry, rz):
    cx, cy, cz = center
    px, nx = (cx + rx, cy, cz), (cx - rx, cy, cz)
    py, ny = (cx, cy + ry, cz), (cx, cy - ry, cz)
    pz, nz = (cx, cy, cz + rz), (cx, cy, cz - rz)
    tris = []
    for a in (px, nx):
        for b in (py, ny):
            for c in (pz, nz):
                tris.append((a, b, c))
    return oriented(tris)


def spike(base_center, tip, radius, axis_a, axis_b):
    """A pyramid with a square base, pointing from base_center to tip."""
    base_center = np.array(base_center, float)
    a, b = np.array(axis_a, float) * radius, np.array(axis_b, float) * radius
    base = [tuple(base_center + a), tuple(base_center + b), tuple(base_center - a), tuple(base_center - b)]
    return oriented(fan(tuple(tip), base) + [(base[0], base[1], base[2]), (base[0], base[2], base[3])])


def write_obj(path, tris, comment):
    with open(path, "w") as f:
        f.write(f"# {comment}\n# Placeholder generated by tools/generate_placeholder_assets.py\n")
        for tri in tris:
            for v in tri:
                f.write("v %.5f %.5f %.5f\n" % tuple(v))
        for i in range(len(tris)):
            f.write("f %d %d %d\n" % (3 * i + 1, 3 * i + 2, 3 * i + 3))


def player_hull():
    # spindle body: nose at +x, two rings, flat tail
    nose = (1.3, 0.0, 0.0)
    front = ring_x(0.25, 0.28, 0.42, 6)
    rear = ring_x(-0.85, 0.22, 0.32, 6)
    tail = (-0.9, 0.0, 0.0)
    body = oriented(fan(nose, front) + strip(front, rear) + fan(tail, rear))

    cockpit = octahedron((0.45, 0.24, 0.0), 0.35, 0.12, 0.16)
    dorsal_fin = prism([(-0.85, 0.15, 0), (-0.25, 0.15, 0), (-0.8, 0.7, 0)], (0, 0, 0.05))
    ventral_fin = prism([(-0.8, -0.15, 0), (-0.4, -0.15, 0), (-0.75, -0.45, 0)], (0, 0, 0.04))
    wings = []
    for side in (1, -1):
        wings += prism([(-0.55, -0.02, 0.3 * side), (0.15, -0.02, 0.3 * side), (-0.8, -0.08, 1.15 * side)],
                       (0, 0.04, 0))
    return body + cockpit + dorsal_fin + ventral_fin + wings


def player_engine():
    return box((-0.97, 0.0, 0.0), (0.08, 0.14, 0.2))


def drone_body():
    body = octahedron((0, 0, 0), 0.75, 0.55, 0.55)
    spikes = []
    for direction in ((0, 1, 0), (0, -1, 0), (-1, 0, 0)):
        d = np.array(direction, float)
        side = np.array((0, 0, 1.0))
        other = np.cross(d, side)
        spikes += spike(d * 0.35, d * 1.05, 0.14, side, other)
    return body + spikes


def drone_core():
    return octahedron((0.15, 0, -0.5), 0.2, 0.2, 0.15)


def saucer_body():
    top = (0, 0.3, 0)
    rim = ring_y(0.0, 0.95, 10)
    bottom = (0, -0.22, 0)
    return oriented(fan(top, rim) + fan(bottom, rim))


def saucer_dome():
    dome_ring = ring_y(0.2, 0.38, 8)
    return oriented(fan((0, 0.52, 0), dome_ring) + fan((0, 0.2, 0), dome_ring))


# --- TEXTURES ---
# Tileable horizontally and vertically: the background scrolls forever.

def write_png(path, rgb):
    height, width, _ = rgb.shape
    raw = b"".join(b"\x00" + rgb[y].tobytes() for y in range(height))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(raw, 9)))
        f.write(chunk(b"IEND", b""))


def periodic_noise(width, height, cells_x, cells_y, rng):
    """Value noise that wraps around: the lattice repeats every cells_x by cells_y."""
    lattice = rng.random((cells_y, cells_x))
    x = np.arange(width) * cells_x / width
    y = np.arange(height) * cells_y / height
    x0, y0 = np.floor(x).astype(int), np.floor(y).astype(int)
    fx, fy = x - x0, y - y0
    fx, fy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
    x1, y1 = (x0 + 1) % cells_x, (y0 + 1) % cells_y
    top = lattice[y0][:, x0] * (1 - fx) + lattice[y0][:, x1] * fx
    bottom = lattice[y1][:, x0] * (1 - fx) + lattice[y1][:, x1] * fx
    return top * (1 - fy)[:, None] + bottom * fy[:, None]


def fbm(width, height, rng, octaves=5):
    total = np.zeros((height, width))
    amplitude, weight = 1.0, 0.0
    for octave in range(octaves):
        cells = 4 * 2 ** octave
        total += periodic_noise(width, height, cells * 2, cells, rng) * amplitude
        weight += amplitude
        amplitude *= 0.5
    return total / weight


def add_stars(image, rng, count, brightness, glow):
    height, width, _ = image.shape
    for _ in range(count):
        x, y = rng.integers(0, width), rng.integers(0, height)
        b = brightness * rng.uniform(0.4, 1.0)
        tint = np.array([1.0, 1.0, 1.0]) - rng.uniform(0, 0.25) * np.array(rng.permutation([1.0, 0.5, 0.0]))
        image[y, x] += b * tint
        if glow and b > brightness * 0.75:
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                image[(y + dy) % height, (x + dx) % width] += b * 0.35 * tint


def nebula_layer(width, height, rng):
    clouds = np.clip((fbm(width, height, rng) - 0.45) * 2.2, 0, 1) ** 2
    tint = fbm(width, height, rng, octaves=3)
    purple = np.array([0.55, 0.16, 0.70])
    blue = np.array([0.08, 0.28, 0.62])
    color = clouds[..., None] * (purple * tint[..., None] + blue * (1 - tint[..., None]))
    color += np.array([0.01, 0.01, 0.025])  # space is not pure black
    add_stars(color, rng, 2500, 0.35, glow=False)
    return color


def star_layer(width, height, rng, count, brightness):
    image = np.zeros((height, width, 3))
    add_stars(image, rng, count, brightness, glow=True)
    return image


def to_rgb8(image):
    return (np.clip(image, 0, 1) * 255).astype(np.uint8)


def main():
    os.makedirs(MODELS_DIR, exist_ok=True)
    os.makedirs(TEXTURES_DIR, exist_ok=True)

    write_obj(f"{MODELS_DIR}/player_hull.obj", player_hull(), "Player ship hull, nose towards +x")
    write_obj(f"{MODELS_DIR}/player_engine.obj", player_engine(), "Player engine glow")
    write_obj(f"{MODELS_DIR}/drone_body.obj", drone_body(), "Drone enemy body")
    write_obj(f"{MODELS_DIR}/drone_core.obj", drone_core(), "Drone enemy glowing eye, facing the camera (-z)")
    write_obj(f"{MODELS_DIR}/saucer_body.obj", saucer_body(), "Saucer enemy body")
    write_obj(f"{MODELS_DIR}/saucer_dome.obj", saucer_dome(), "Saucer enemy glowing dome")

    rng = np.random.default_rng(42)
    width, height = 1024, 512
    write_png(f"{TEXTURES_DIR}/space_nebula.png", to_rgb8(nebula_layer(width, height, rng)))
    write_png(f"{TEXTURES_DIR}/space_stars_far.png", to_rgb8(star_layer(width, height, rng, 900, 0.6)))
    write_png(f"{TEXTURES_DIR}/space_stars_near.png", to_rgb8(star_layer(width, height, rng, 160, 1.0)))
    print("Placeholder assets written to assets/game/")


if __name__ == "__main__":
    main()
